function compare(o1, o2, p = '') {
  let m = [];
  for (let k in o1) {
    let currentPath = p ? p + '.' + k : k;
    if (!o2 || o2[k] === undefined) {
      m.push(currentPath);
      continue;
    }
    if (typeof o1[k] === 'object' && o1[k] !== null && !Array.isArray(o1[k])) {
      m = m.concat(compare(o1[k], o2[k], currentPath));
    } else if (Array.isArray(o1[k])) {
      if (!Array.isArray(o2[k])) {
        m.push(currentPath + ' (not array in ar)');
      } else {
        for (let i = 0; i < o1[k].length; i++) {
          if (typeof o1[k][i] === 'object') {
            m = m.concat(compare(o1[k][i], o2[k][i] || {}, currentPath + '[' + i + ']'));
          }
        }
      }
    } else if (typeof o2[k] === 'string' && o2[k].trim() === '') {
      m.push(currentPath + ' (empty string)');
    } else if (typeof o2[k] === 'string' && o2[k] === o1[k] && o2[k].trim() !== '' && !currentPath.includes('href') && !currentPath.includes('key')) {
      // It is exactly the same as French and it's not empty, not a link. Might be untranslated.
      m.push(currentPath + ' (same as fr: ' + o2[k].substring(0, 20) + '...)');
    }
  }
  return m;
}
